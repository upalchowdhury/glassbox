"""Render the blueprint's factual sections from a run artifact.

The blueprint used to state its numbers in hand-typed prose. Every one of them
was wrong: a parameter count from an older architecture, a vocabulary size that
matched no version of the code, loss curves nobody could reproduce, seven
assertions that did not exist. The numbers were not wrong because anyone lied.
They were wrong because a human typed them once and the code kept moving.

So this module is the fix for the root cause, not for the numbers. It reads
``runs/latest.json`` - the artifact ``glassbox.export`` writes - and renders the
factual sections of the document as Markdown. Nothing here computes a model
quantity, and nothing here has a fallback value: if a field is missing from the
artifact the table says so in the output instead of substituting something
plausible. A claim you cannot trace to a field in the artifact is a claim this
module will not print.

Usage::

    python -m glassbox.report                              # print to stdout
    python -m glassbox.report --section results             # one section
    python -m glassbox.report --update Glassbox_Course_Blueprint.md

``--update`` rewrites only the text between paired HTML comments::

    <!-- BEGIN generated:results -->
    ...replaced...
    <!-- END generated:results -->

Everything outside those markers is hand-written prose and is never touched.
The rewrite is idempotent: running it twice produces a byte-identical file.
"""

from __future__ import annotations

import argparse
import json
