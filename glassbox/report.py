REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RUN = REPO_ROOT / "runs" / "latest.json"

#: Printed wherever the artifact does not carry the field. Never a number.
ABSENT = "absent from artifact"

BEGIN = "<!-- BEGIN generated:{name} -->"
END = "<!-- END generated:{name} -->"
MARKER_RE = re.compile(
    r"(?P<begin><!--\s*BEGIN generated:(?P<name>[a-z0-9_-]+)\s*-->)"
    r"(?P<body>.*?)"
    r"(?P<end><!--\s*END generated:(?P=name)\s*-->)",
    re.DOTALL,
)

GENERATED_NOTE = (
    "<!-- Generated by `python -m glassbox.report --update` from "
    "runs/latest.json. Do not edit by hand; edit the run, then regenerate. -->"
)


# --------------------------------------------------------------------------
# Artifact access. Every read goes through _get so a missing field degrades to
# a printed "absent from artifact" rather than a KeyError or an invented value.
# --------------------------------------------------------------------------


def load_run(path: Path = DEFAULT_RUN) -> Dict[str, Any]:
    """Load a run artifact written by :mod:`glassbox.export`."""
    with open(path, "r", encoding="utf-8") as fh:
        run = json.load(fh)
    if not isinstance(run, dict):
        raise ValueError(f"{path}: run artifact must be a JSON object")
    return run


def _get(obj: Any, *path: Any) -> Any:
    """Walk dict keys and list indices, returning None at the first miss."""
    cur = obj
    for step in path:
        if isinstance(step, int) and isinstance(cur, list):
            if -len(cur) <= step < len(cur):
                cur = cur[step]
                continue
            return None
        if isinstance(cur, dict) and step in cur:
            cur = cur[step]
            continue
        return None
    return cur


# --------------------------------------------------------------------------
# Display formatting. Rounding happens here and only here; the artifact keeps
# the full-precision values.
# --------------------------------------------------------------------------


def num(value: Any, decimals: int = 4) -> str:
    """Format one number for display, or say the field is missing."""
    if value is None:
        return ABSENT
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        return f"{value:.{decimals}f}"
    return str(value)


def pct(value: Any, decimals: int = 1) -> str:
    if value is None:
        return ABSENT
    return f"{value * 100:.{decimals}f}%"


def arrow(start: Any, end: Any, decimals: int = 4) -> str:
    return f"{num(start, decimals)} -> {num(end, decimals)}"


def _compact(value: Any, decimals: int = 7, maxlen: int = 40) -> str:
    """A short, cell-safe rendering of an arbitrary JSON value."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        # Keep a trailing ".0" so a float hyperparameter never reads as an int.
        if value.is_integer() and abs(value) < 1e6:
            return f"{value:.1f}"
        return f"{value:.{decimals}g}"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return value if len(value) <= maxlen else value[: maxlen - 1] + "\u2026"
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(not isinstance(v, (list, dict)) for v in value):
            shown = ", ".join(_compact(v, decimals, maxlen) for v in value[:4])
            more = f", \u2026 (+{len(value) - 4})" if len(value) > 4 else ""
            return f"[{shown}{more}]"
        return f"[{len(value)} entries]"
    if isinstance(value, dict):
        return "{" + ", ".join(
            f"{k}: {_compact(v, decimals, maxlen)}"
            for k, v in list(value.items())[:3]
        ) + ("}" if len(value) <= 3 else ", \u2026}")
    return str(value)


def _approx_seconds(value: Any) -> str:
    """Wall-clock rounded to the nearest 10 seconds, as an approximation."""
    try:
        seconds = float(value)
    except (TypeError, ValueError):
        return "unrecorded"
    return f"about {int(round(seconds / 10.0) * 10)} s on one CPU"


def cell(text: str) -> str:
    """Make a string safe inside a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    """Render a Markdown table. Rows are already-formatted strings."""
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(str(c)) for c in row) + " |")
    return "\n".join(out)


